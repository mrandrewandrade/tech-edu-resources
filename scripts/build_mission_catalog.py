"""Validate the mission catalogue and generate website and game UI data."""

from __future__ import annotations

import argparse
import html
import json
import sys
from pathlib import Path
from typing import Any

import yaml


ROOT = Path(__file__).resolve().parents[1]
SITE = ROOT / "site"
SOURCE = SITE / "data" / "mission-catalog.yml"
JSON_OUTPUT = SITE / "assets" / "missions" / "mission-catalog.json"
TABLE_OUTPUT = SITE / "includes" / "generated" / "mission-stat-table.md"
STAT_KEYS = ("circuits", "coding", "measurement", "building", "troubleshooting")


def site_source(href: str) -> Path:
    source = href.split("#", 1)[0]
    return SITE / source


def rendered_href(href: str) -> str:
    source, marker, anchor = href.partition("#")
    rendered = str(Path(source).with_suffix(".html")).replace("\\", "/")
    suffix = f"#{anchor}" if marker else ""
    return f"../{rendered}{suffix}"


def load_catalog() -> dict[str, Any]:
    data = yaml.safe_load(SOURCE.read_text(encoding="utf-8")) or {}
    if not isinstance(data, dict):
        raise ValueError("Mission catalogue must be a YAML mapping")
    return data


def validate(data: dict[str, Any]) -> list[dict[str, Any]]:
    readiness = data.get("readiness_levels", {})
    regions = data.get("regions", {})
    stat_labels = data.get("stat_labels", {})
    missions = data.get("missions", [])
    if not isinstance(readiness, dict) or not readiness:
        raise ValueError("readiness_levels must contain at least one entry")
    if not isinstance(regions, dict) or not regions:
        raise ValueError("regions must contain at least one entry")
    if tuple(stat_labels) != STAT_KEYS:
        raise ValueError(f"stat_labels must use this order: {', '.join(STAT_KEYS)}")
    if not isinstance(missions, list) or not missions:
        raise ValueError("missions must contain at least one mission")
    pattern = data.get("mission_pattern", {})
    stages = pattern.get("stages", []) if isinstance(pattern, dict) else []
    if not isinstance(stages, list) or not stages:
        raise ValueError("mission_pattern.stages must contain at least one stage")
    stage_ids = [str(stage.get("id", "")) for stage in stages if isinstance(stage, dict)]
    if any(not stage_id for stage_id in stage_ids) or len(stage_ids) != len(set(stage_ids)):
        raise ValueError("mission_pattern stage ids must be present and unique")

    region_ids = {str(region_id) for region_id in regions}
    ids: set[str] = set()
    for mission in missions:
        mission_id = str(mission.get("id", ""))
        if not mission_id or mission_id in ids:
            raise ValueError(f"Missing or duplicate mission id: {mission_id!r}")
        ids.add(mission_id)
        if mission.get("readiness") not in readiness:
            raise ValueError(f"{mission_id}: unknown readiness {mission.get('readiness')!r}")
        if mission.get("region") not in region_ids:
            raise ValueError(f"{mission_id}: unknown game region {mission.get('region')!r}")
        effort = mission.get("effort")
        if not isinstance(effort, int) or not 1 <= effort <= 5:
            raise ValueError(f"{mission_id}: effort must be an integer from 1 to 5")
        stats = mission.get("stats", {})
        if tuple(stats) != STAT_KEYS:
            raise ValueError(f"{mission_id}: stats must use this order: {', '.join(STAT_KEYS)}")
        for key, score in stats.items():
            if not isinstance(score, int) or not 0 <= score <= 5:
                raise ValueError(f"{mission_id}: {key} must be an integer from 0 to 5")
        href = str(mission.get("href", ""))
        if not href or not site_source(href).is_file():
            raise ValueError(f"{mission_id}: missing website source {href!r}")

    for mission in missions:
        for prerequisite in mission.get("prerequisites", []):
            if prerequisite not in ids:
                raise ValueError(f"{mission['id']}: unknown prerequisite {prerequisite!r}")
    return sorted(missions, key=lambda item: (item.get("order", 1000), item["id"]))


def score(value: int) -> str:
    return f'<span class="mission-score score-{value}">{value}</span>'


def generate_table(data: dict[str, Any], missions: list[dict[str, Any]]) -> str:
    readiness = data["readiness_levels"]
    lines = [
        "<!-- Generated by scripts/build_mission_catalog.py. Do not edit directly. -->",
        "::: {.mission-stat-board}",
        "| Mission | Readiness | Effort | Circuits | Code | Measure | Build | Debug |",
        "|:--|:--:|:--:|:--:|:--:|:--:|:--:|:--:|",
    ]
    for mission in missions:
        ready = readiness[mission["readiness"]]
        title = html.escape(str(mission["title"]))
        href = str(mission["href"])
        ready_label = html.escape(str(ready["label"]))
        ready_class = html.escape(str(ready["css_class"]))
        stats = mission["stats"]
        cells = [
            f"[{title}](../../{href})",
            f'<span class="mission-readiness {ready_class}">{ready_label}</span>',
            score(mission["effort"]),
            *(score(stats[key]) for key in STAT_KEYS),
        ]
        lines.append("| " + " | ".join(cells) + " |")
    lines.extend([":::", ""])
    return "\n".join(lines)


def generate_json(data: dict[str, Any], missions: list[dict[str, Any]]) -> str:
    readiness = data["readiness_levels"]
    payload = {
        "version": data.get("version", 1),
        "generated_from": "site/data/mission-catalog.yml",
        "stat_labels": data["stat_labels"],
        "readiness_levels": readiness,
        "regions": data["regions"],
        "mission_pattern": data["mission_pattern"],
        "missions": [
            {
                **mission,
                "href": rendered_href(str(mission["href"])),
                "source": str(mission["href"]).split("#", 1)[0],
                "readiness_label": readiness[mission["readiness"]]["label"],
                "teacher_gate": bool(readiness[mission["readiness"]]["teacher_gate"]),
            }
            for mission in missions
        ],
    }
    return json.dumps(payload, indent=2, ensure_ascii=False) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)

    data = load_catalog()
    missions = validate(data)
    rendered_json = generate_json(data, missions)
    rendered_table = generate_table(data, missions)

    if args.check:
        stale = []
        if not JSON_OUTPUT.exists() or JSON_OUTPUT.read_text(encoding="utf-8") != rendered_json:
            stale.append(JSON_OUTPUT)
        if not TABLE_OUTPUT.exists() or TABLE_OUTPUT.read_text(encoding="utf-8") != rendered_table:
            stale.append(TABLE_OUTPUT)
        if stale:
            for path in stale:
                print(f"Stale generated file: {path.relative_to(ROOT)}", file=sys.stderr)
            return 1
        print(f"Mission catalogue is current: {len(missions)} missions")
        return 0

    JSON_OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    TABLE_OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    JSON_OUTPUT.write_text(rendered_json, encoding="utf-8")
    TABLE_OUTPUT.write_text(rendered_table, encoding="utf-8")
    pilot_count = sum(bool(mission.get("pilot")) for mission in missions)
    print(f"Built mission catalogue: {len(missions)} missions, {pilot_count} pilot missions")
    return 0


if __name__ == "__main__":
    try:
        raise SystemExit(main())
    except (OSError, ValueError, KeyError, TypeError, yaml.YAMLError) as exc:
        print(exc, file=sys.stderr)
        raise SystemExit(1)
